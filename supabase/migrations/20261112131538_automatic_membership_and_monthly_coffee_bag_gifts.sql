
-- Earned membership lasts at least 12 months; manually assigned tiers take priority.
create table public.membership_auto_awards (
 user_id uuid primary key references auth.users(id) on delete cascade,
 tier text not null check (tier in ('bronze','silver','gold')),
 awarded_at timestamptz not null default now(),
 protected_until timestamptz not null
);
alter table public.membership_auto_awards enable row level security;
revoke all on public.membership_auto_awards from public,anon,authenticated;
grant select on public.membership_auto_awards to authenticated;
grant all on public.membership_auto_awards to service_role;
create policy "read own membership award" on public.membership_auto_awards
  for select to authenticated using (user_id=(select auth.uid()));

-- Per-month packing queue, idempotent per member and gift type.
create table public.membership_coffee_bag_gifts (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 order_id uuid not null references public.orders(id) on delete cascade,
 gift_month date not null,
 gift_kind text not null check (gift_kind in ('bronze_welcome','monthly')),
 quantity integer not null check (quantity between 1 and 2),
 status text not null default 'pending' check (status in ('pending','packed')),
 created_at timestamptz not null default now(),
 packed_at timestamptz,
 constraint membership_gifts_month_unique unique(user_id,gift_month,gift_kind)
);
create unique index membership_gifts_bronze_once
 on public.membership_coffee_bag_gifts(user_id) where gift_kind='bronze_welcome';
create index membership_gifts_order_idx on public.membership_coffee_bag_gifts(order_id);
create index membership_gifts_queue_idx on public.membership_coffee_bag_gifts(status,created_at);
alter table public.membership_coffee_bag_gifts enable row level security;
revoke all on public.membership_coffee_bag_gifts from public,anon,authenticated;
grant all on public.membership_coffee_bag_gifts to service_role;

-- Trigger performs award and gift reservation when a linked order becomes paid.
create or replace function private.membership_sync_paid_order()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
 v_spend bigint;
 v_tier text;
 v_stored text;
 v_manual text;
 v_effective text;
 v_value integer;
 v_month date;
begin
 if new.user_id is null then return new; end if;
 if tg_op='UPDATE'
    and old.payment_status is not distinct from new.payment_status
    and old.order_status is not distinct from new.order_status
    and old.user_id is not distinct from new.user_id then return new; end if;

 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(new.user_id::text,20261112));

 select coalesce(sum(greatest(0,coalesce(o.product_subtotal,o.subtotal,0)-coalesce(o.discount_amount,0))),0)
 into v_spend from public.orders o
 where o.user_id=new.user_id and o.payment_status='paid'
   and o.order_status<>'cancelled'
   and o.created_at>=now()-interval '12 months';

 v_tier:=case when v_spend>=360000 then 'gold'
              when v_spend>=180000 then 'silver'
              when v_spend>=60000 then 'bronze' else 'general' end;

 if new.payment_status in ('refunded','cancelled') or new.order_status='cancelled' then
   -- Refunded orders cannot qualify toward the member tier or gifts.
   if v_tier='general' then
     delete from public.membership_auto_awards where user_id=new.user_id;
   else
     update public.membership_auto_awards set tier=v_tier
       where user_id=new.user_id and
       (case tier when 'gold' then 3 when 'silver' then 2 else 1 end)>
       (case v_tier when 'gold' then 3 when 'silver' then 2 else 1 end);
   end if;
   delete from public.membership_coffee_bag_gifts where order_id=new.id and status='pending';
 elsif new.payment_status='paid' and new.order_status<>'cancelled' and v_tier<>'general' then
   insert into public.membership_auto_awards(user_id,tier,awarded_at,protected_until)
      values(new.user_id,v_tier,now(),now()+interval '12 months')
   on conflict(user_id) do update set tier=excluded.tier,
      awarded_at=excluded.awarded_at,protected_until=excluded.protected_until
   where public.membership_auto_awards.protected_until<=now() or
     (case public.membership_auto_awards.tier when 'gold' then 3 when 'silver' then 2 else 1 end) <
     (case excluded.tier when 'gold' then 3 when 'silver' then 2 else 1 end);
 end if;

 if new.payment_status<>'paid' or new.order_status='cancelled' or new.order_source<>'online'
   then return new; end if;

 select tier into v_manual from public.vip_customers where user_id=new.user_id;
 select a.tier into v_stored from public.membership_auto_awards a
  where a.user_id=new.user_id and a.protected_until>now();
 v_effective:=coalesce(v_manual,v_stored,'general');
 if v_effective in ('vip','private') then v_effective:='gold'; end if;
 v_value:=greatest(0,coalesce(new.product_subtotal,new.subtotal,0)-coalesce(new.discount_amount,0));
 v_month:=date_trunc('month',now() at time zone 'Asia/Seoul')::date;

 if v_effective='bronze' and v_spend>=60000 then
   insert into public.membership_coffee_bag_gifts(user_id,order_id,gift_month,gift_kind,quantity)
     values(new.user_id,new.id,v_month,'bronze_welcome',1) on conflict do nothing;
 elsif v_effective='silver' and v_value>=30000 then
   insert into public.membership_coffee_bag_gifts(user_id,order_id,gift_month,gift_kind,quantity)
     values(new.user_id,new.id,v_month,'monthly',1) on conflict do nothing;
 elsif v_effective='gold' then
   insert into public.membership_coffee_bag_gifts(user_id,order_id,gift_month,gift_kind,quantity)
     values(new.user_id,new.id,v_month,'monthly',1) on conflict do nothing;
 elsif v_effective='zero_black' then
   insert into public.membership_coffee_bag_gifts(user_id,order_id,gift_month,gift_kind,quantity)
     values(new.user_id,new.id,v_month,'monthly',2) on conflict do nothing;
 end if;
 return new;
end;
$$;
revoke all on function private.membership_sync_paid_order() from public,anon,authenticated;
drop trigger if exists membership_paid_order_sync on public.orders;
create trigger membership_paid_order_sync
  after insert or update of payment_status,order_status,user_id on public.orders
  for each row execute function private.membership_sync_paid_order();

-- Existing purchases generate auto tiers, but historical gifts are never retroactively sent.
insert into public.membership_auto_awards(user_id,tier,awarded_at,protected_until)
select totals.user_id,
 case when totals.spent>=360000 then 'gold'
      when totals.spent>=180000 then 'silver' else 'bronze' end,
 now(),now()+interval '12 months'
from (
 select o.user_id,sum(greatest(0,coalesce(o.product_subtotal,o.subtotal,0)-coalesce(o.discount_amount,0))) spent
 from public.orders o
 where o.user_id is not null and o.payment_status='paid'
   and o.order_status<>'cancelled' and o.created_at>=now()-interval '12 months'
 group by o.user_id
) totals where totals.spent>=60000
on conflict(user_id) do nothing;
